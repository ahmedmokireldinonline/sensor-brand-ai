export function translateText(value: string, language: Language, arabicOverride?: string) {
  if (language === "en") return value;
  return arabicOverride ?? translations[value] ?? value;
}

export function reverseTranslation(value: string) {
  return Object.entries(translations).find(([, arabic]) => arabic === value)?.[0] ?? value;
}
