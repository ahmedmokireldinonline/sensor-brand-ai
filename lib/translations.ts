export type TranslationKey =
  | `common.${keyof typeof messages.common}`
  | `shell.${keyof typeof messages.shell}`
  | `dashboard.${keyof Omit<typeof messages.dashboard, "metrics">}`
  | `dashboard.metrics.${keyof typeof messages.dashboard.metrics}`
  | `dashboard.metrics.${keyof typeof messages.dashboard.metrics}.${"detail"}`
  | `login.${keyof typeof messages.login}`
  | `analytics.${keyof typeof messages.analytics}`
  | `sync.${keyof typeof messages.sync}`
  | `workspaces.${keyof typeof messages.workspaces}`
  | `sources.${keyof typeof messages.sources}`
  | `landing.${keyof typeof messages.landing}`;

export function getMessage(key: TranslationKey) {
  const parts = key.split(".");
  let value: unknown = messages;
  for (const part of parts) value = (value as Record<string, unknown>)[part];
  if (typeof value === "object" && value !== null && "en" in value && "ar" in value) return value as { en: string; ar: string };
  throw new Error(`Unknown translation key: ${key}`);
}
